/**
 * Derives a full Material 3 Light & Dark Color Scheme from any single primary hex color.
 */
export function generateM3FromPrimaryHex(primaryHex: string): {
  light: Material3ColorScheme;
  dark: Material3ColorScheme;
} {
  // Simple HSL-based tint generator
  const hex = primaryHex.replace("#", "");
  const r = parseInt(hex.substring(0, 2), 16) || 103;
  const g = parseInt(hex.substring(2, 4), 16) || 80;
  const b = parseInt(hex.substring(4, 6), 16) || 164;

  const hexPad = (num: number) => Math.min(255, Math.max(0, Math.round(num))).toString(16).padStart(2, "0");

  const mix = (c1: [number, number, number], c2: [number, number, number], weight: number) => {
    return `#${hexPad(c1[0] * (1 - weight) + c2[0] * weight)}${hexPad(
      c1[1] * (1 - weight) + c2[1] * weight
    )}${hexPad(c1[2] * (1 - weight) + c2[2] * weight)}`;
  };

  const pRgb: [number, number, number] = [r, g, b];
  const white: [number, number, number] = [255, 255, 255];
  const black: [number, number, number] = [20, 18, 24];

  const primaryContainerLight = mix(pRgb, white, 0.82);
  const onPrimaryContainerLight = mix(pRgb, black, 0.7);

  const primaryDark = mix(pRgb, white, 0.45);
  const primaryContainerDark = mix(pRgb, black, 0.45);
  const onPrimaryContainerDark = mix(pRgb, white, 0.85);

  return {
    light: {
      primary: `#${hex}`,
      onPrimary: "#FFFFFF",
      primaryContainer: primaryContainerLight,
      onPrimaryContainer: onPrimaryContainerLight,
      secondary: mix(pRgb, [100, 100, 120], 0.4),
      onSecondary: "#FFFFFF",
      secondaryContainer: mix(pRgb, white, 0.88),
      onSecondaryContainer: mix(pRgb, black, 0.65),
      tertiary: mix(pRgb, [125, 82, 96], 0.5),
      onTertiary: "#FFFFFF",
      tertiaryContainer: mix(pRgb, white, 0.9),
      onTertiaryContainer: mix(pRgb, black, 0.75),
      background: "#FEF7FF",
      onBackground: "#1D1B20",
      surface: "#FEF7FF",
      onSurface: "#1D1B20",
      surfaceVariant: mix(pRgb, white, 0.92),
      onSurfaceVariant: "#49454F",
      outline: "#79747E",
      outlineVariant: "#CAC4D0",
      error: "#B3261E",
      onError: "#FFFFFF",
      errorContainer: "#F9DEDC",
      onErrorContainer: "#410E0B",
    },
    dark: {
      primary: primaryDark,
      onPrimary: mix(pRgb, black, 0.8),
      primaryContainer: primaryContainerDark,
      onPrimaryContainer: onPrimaryContainerDark,
      secondary: mix(pRgb, white, 0.65),
      onSecondary: mix(pRgb, black, 0.75),
      secondaryContainer: mix(pRgb, black, 0.5),
      onSecondaryContainer: mix(pRgb, white, 0.85),
      tertiary: mix(pRgb, [239, 184, 200], 0.6),
      onTertiary: mix(pRgb, black, 0.7),
      tertiaryContainer: mix(pRgb, black, 0.4),
      onTertiaryContainer: mix(pRgb, white, 0.88),
      background: "#141218",
      onBackground: "#E6E0E9",
      surface: "#141218",
      onSurface: "#E6E0E9",
      surfaceVariant: "#49454F",
      onSurfaceVariant: "#CAC4D0",
      outline: "#938F99",
      outlineVariant: "#49454F",
      error: "#F2B8B5",
      onError: "#601410",
      errorContainer: "#8C1D18",
      onErrorContainer: "#F9DEDC",
    },
  };
}
