export function createComponentInstance(type: string): AndroidComponent {
  const def = COMPONENT_DEFINITIONS.find((c) => c.type === type) || COMPONENT_DEFINITIONS[0];
  const uniqueId = `comp_${type.toLowerCase().replace(/[^a-z0-9]/g, "_")}_${Math.random().toString(36).substring(2, 7)}`;
  const cleanName = `${type.replace(/[^a-zA-Z0-9]/g, "")}${Math.floor(100 + Math.random() * 900)}`;

  return {
    id: uniqueId,
    type: def.type,
    name: cleanName,
    category: def.category,
    props: { ...def.defaultProps },
    children: def.isContainer ? [] : undefined,
  };
}
