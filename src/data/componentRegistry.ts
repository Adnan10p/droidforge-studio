export const ALL_CATEGORIES = [...VISIBLE_CATEGORIES, ...NON_VISIBLE_CATEGORIES];

export function isNonVisibleCategory(category: string): boolean {
  return NON_VISIBLE_CATEGORIES.some(c => c.id === category);
}

export function isNonVisibleComponent(
  typeOrDef: string | ComponentDefinition | { type: string; category?: string }
): boolean {
  const typeStr = typeof typeOrDef === "string" ? typeOrDef : (typeOrDef as any).type;
  if (typeStr && isNonVisibleTypeName(typeStr)) {
    return true;
  }
  if (typeof typeOrDef !== "string" && (typeOrDef as any).isVisible !== undefined) {
    return !(typeOrDef as any).isVisible;
  }
  const def = COMPONENT_DEFINITIONS.find((c) => c.type === typeStr || c.name === typeStr);
  if (def && def.isVisible !== undefined) return !def.isVisible;
  if (typeof typeOrDef !== "string" && (typeOrDef as any).category) {
    return isNonVisibleCategory((typeOrDef as any).category);
  }
  if (def) return isNonVisibleCategory(def.category);
  return false;
}


