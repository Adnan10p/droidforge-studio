export function isContainerComponent(comp: AndroidComponent | string | null | undefined): boolean {
  if (!comp) return false;
  const compType = typeof comp === "string" ? comp : comp.type;
  const compName = typeof comp === "string" ? comp : comp.name;
  const compId = typeof comp === "object" ? comp.id : "";

  if (compId === "root" || compType === "Screen" || compType === "Root" || compType === "ScrollView") return true;

  const normType = compType.toLowerCase().replace(/[\s_-]+/g, "");

  // Explicit non-containers:
  if (
    normType === "space" ||
    normType.includes("space") ||
    normType.includes("button") ||
    normType.includes("label") ||
    normType.includes("text") ||
    normType.includes("input") ||
    normType.includes("image") ||
    normType.includes("ad") ||
    normType.includes("slider") ||
    normType.includes("check") ||
    normType.includes("switch") ||
    normType.includes("radio") ||
    normType.includes("rating") ||
    normType.includes("progress") ||
    normType.includes("loader") ||
    normType.includes("picker")
  ) {
    if (
      !normType.includes("card") &&
      !normType.includes("layout") &&
      !normType.includes("container") &&
      !normType.includes("scroll")
    ) {
      return false;
    }
  }

  const def = COMPONENT_DEFINITIONS.find((c) => c.type === compType || c.name === compName);
  if (def && def.isContainer !== undefined) {
    return def.isContainer;
  }

  if (typeof comp === "object" && Array.isArray(comp.children)) {
    return comp.children.length > 0;
  }

  return false;
}

export function findComponentAndParent(
  targetId: string,
  current: AndroidComponent,
  parent: AndroidComponent | null = null
): { target: AndroidComponent; parent: AndroidComponent | null } | null {
  if (current.id === targetId) {
    return { target: current, parent };
  }
  if (current.children) {
    for (const child of current.children) {
      const res = findComponentAndParent(targetId, child, current);
      if (res) return res;
    }
  }
  return null;
}

export function resolveContainerTargetId(
  targetId: string | undefined,
  rootComponent: AndroidComponent
): string {
  const rawTarget = targetId || rootComponent.id;
  const match = findComponentAndParent(rawTarget, rootComponent);
  if (!match) return rootComponent.id;

  let curr = match.target;
  let currParent = match.parent;

  while (curr && !isContainerComponent(curr)) {
    if (!currParent) return rootComponent.id;
    const parentMatch = findComponentAndParent(currParent.id, rootComponent);
    curr = currParent;
    currParent = parentMatch?.parent || null;
  }

  return curr.id;
}

export function createComponentInstance(type: string): AndroidComponent {
  const def = COMPONENT_DEFINITIONS.find((c) => c.type === type || c.name === type) || COMPONENT_DEFINITIONS[0];
  const uniqueId = `comp_${def.type.toLowerCase().replace(/[^a-z0-9]/g, "_")}_${Math.random().toString(36).substring(2, 7)}`;
  const cleanName = `${def.name.replace(/[^a-zA-Z0-9]/g, "")}${Math.floor(100 + Math.random() * 900)}`;

  return {
    id: uniqueId,
    type: def.type,
    name: cleanName,
    category: def.category,
    props: { ...def.defaultProps },
    children: def.isContainer ? [] : undefined,
  };
}

